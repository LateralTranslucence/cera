/**
 * Writes .env.local from the running local Supabase stack (`supabase start`
 * in the site, or at this repository's root). Keeps an existing CERA_PREVIEW_SECRET.
 *
 *   npm run env -w cera-next-site
 */
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { randomBytes } from 'node:crypto';
import { join } from 'node:path';

const site = join(import.meta.dirname, '..');
// Where `supabase start` runs: the site itself when it has its own supabase/
// folder (a site made by create-cera), else this repository's root.
const repoRoot = existsSync(join(site, 'supabase', 'config.toml')) ? site : join(site, '..', '..');
const target = join(site, '.env.local');

function parse(text: string): Record<string, string> {
  const out: Record<string, string> = {};
  for (const line of text.split('\n')) {
    const match = line.match(/^([A-Z0-9_]+)="?(.*?)"?$/);
    if (match) out[match[1]!] = match[2]!;
  }
  return out;
}

const status = parse(execFileSync('supabase', ['status', '-o', 'env'], { cwd: repoRoot, encoding: 'utf8' }));
for (const key of ['API_URL', 'PUBLISHABLE_KEY', 'SECRET_KEY']) {
  if (!status[key]) throw new Error(`supabase status did not report ${key}. Is the stack running?`);
}

const existing = existsSync(target) ? parse(readFileSync(target, 'utf8')) : {};
const previewSecret = existing.CERA_PREVIEW_SECRET ?? randomBytes(24).toString('hex');
// Local admin account created by `npm run seed`. Sign in at /admin with these.
const adminEmail = existing.CERA_ADMIN_EMAIL ?? 'admin@cera.test';
const adminPassword = existing.CERA_ADMIN_PASSWORD ?? randomBytes(12).toString('base64url');
// Form emails go to the stack's test inbox (supabase/config.toml's [local_smtp] smtp_port), unless set otherwise.
const smtpPort = readFileSync(join(repoRoot, 'supabase', 'config.toml'), 'utf8').match(/^\s*smtp_port\s*=\s*(\d+)/m)?.[1];
const smtpUrl = existing.SMTP_URL ?? (smtpPort ? `smtp://127.0.0.1:${smtpPort}` : undefined);
const emailFrom = existing.CERA_EMAIL_FROM ?? 'Cera <no-reply@cera.test>';

writeFileSync(
  target,
  [
    '# Generated by scripts/env.ts from `supabase status`. Local development only.',
    `NEXT_PUBLIC_SUPABASE_URL=${status.API_URL}`,
    `NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY=${status.PUBLISHABLE_KEY}`,
    `SUPABASE_SECRET_KEY=${status.SECRET_KEY}`,
    `CERA_PREVIEW_SECRET=${previewSecret}`,
    `CERA_ADMIN_EMAIL=${adminEmail}`,
    `CERA_ADMIN_PASSWORD=${adminPassword}`,
    ...(smtpUrl ? [`SMTP_URL=${smtpUrl}`] : []),
    `CERA_EMAIL_FROM=${emailFrom}`,
    '',
  ].join('\n'),
);
console.log(`Wrote ${target}`);
