/**
 * Writes .env.local from the running local Supabase stack (`supabase start`
 * at the repo root). Keeps an existing CERA_PREVIEW_SECRET.
 *
 *   npm run env -w cera-next-site
 */
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { randomBytes } from 'node:crypto';
import { join } from 'node:path';

const site = join(import.meta.dirname, '..');
const repoRoot = join(site, '..', '..');
const target = join(site, '.env.local');

function parse(text: string): Record<string, string> {
  const out: Record<string, string> = {};
  for (const line of text.split('\n')) {
    const m = line.match(/^([A-Z0-9_]+)="?(.*?)"?$/);
    if (m) out[m[1]!] = m[2]!;
  }
  return out;
}

const status = parse(execFileSync('supabase', ['status', '-o', 'env'], { cwd: repoRoot, encoding: 'utf8' }));
for (const key of ['API_URL', 'PUBLISHABLE_KEY', 'SECRET_KEY']) {
  if (!status[key]) throw new Error(`supabase status did not report ${key}. Is the stack running?`);
}

const existing = existsSync(target) ? parse(readFileSync(target, 'utf8')) : {};
const previewSecret = existing.CERA_PREVIEW_SECRET ?? randomBytes(24).toString('hex');

writeFileSync(
  target,
  [
    '# Generated by scripts/env.ts from `supabase status`. Local development only.',
    `NEXT_PUBLIC_SUPABASE_URL=${status.API_URL}`,
    `NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY=${status.PUBLISHABLE_KEY}`,
    `SUPABASE_SECRET_KEY=${status.SECRET_KEY}`,
    `CERA_PREVIEW_SECRET=${previewSecret}`,
    '',
  ].join('\n'),
);
console.log(`Wrote ${target}`);
